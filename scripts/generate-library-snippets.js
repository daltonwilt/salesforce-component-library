/**
 * Copies the source of every example* bundle into componentLibrary/snippets.js, so the
 * component library's Example tab shows the code that is actually running in its preview.
 *
 *   npm run snippets          rewrite snippets.js
 *   npm run snippets -- --check   exit 1 if snippets.js is out of date (what CI wants)
 *
 * LWC cannot import a template or a module as text, which is why this is a build step at all.
 * The componentLibrary Jest suite runs the same comparison, so a stale file fails the tests
 * even when nobody remembers to run this.
 */
const fs = require("fs");
const path = require("path");

const LWC_DIR = path.join(__dirname, "..", "force-app", "main", "default", "lwc");
const OUTPUT = path.join(LWC_DIR, "componentLibrary", "snippets.js");

// The order files are shown in, and the language label on each tab.
const FILE_TYPES = [
  { extension: ".html", language: "HTML" },
  { extension: ".js", language: "JavaScript" },
  { extension: ".css", language: "CSS" }
];

function collectSnippets() {
  const bundles = fs
    .readdirSync(LWC_DIR, { withFileTypes: true })
    .filter((entry) => entry.isDirectory() && /^example[A-Z]/.test(entry.name))
    .map((entry) => entry.name)
    .sort();

  const snippets = {};
  for (const bundle of bundles) {
    snippets[bundle] = FILE_TYPES.map(({ extension, language }) => {
      const name = bundle + extension;
      const file = path.join(LWC_DIR, bundle, name);
      return fs.existsSync(file)
        ? { name, language, source: fs.readFileSync(file, "utf8").trimEnd() }
        : null;
    }).filter(Boolean);
  }
  return snippets;
}

function render(snippets) {
  return [
    "// Generated by scripts/generate-library-snippets.js from the example* bundles.",
    "// Do not edit by hand: change the example, then run `npm run snippets`.",
    "export default " + JSON.stringify(snippets, null, 2) + ";",
    ""
  ].join("\n");
}

function main() {
  const expected = render(collectSnippets());

  if (process.argv.includes("--check")) {
    const actual = fs.existsSync(OUTPUT) ? fs.readFileSync(OUTPUT, "utf8") : "";
    if (actual !== expected) {
      console.error(
        "componentLibrary/snippets.js is out of date. Run `npm run snippets`."
      );
      process.exit(1);
    }
    return;
  }

  fs.writeFileSync(OUTPUT, expected);
  console.log("Wrote " + path.relative(process.cwd(), OUTPUT));
}

if (require.main === module) {
  main();
}

module.exports = { collectSnippets, render, OUTPUT };
